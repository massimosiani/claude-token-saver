#!/usr/bin/env python3
"""Render rules and preview/apply bounded CLAUDE.md edits (Python 3.9+, stdlib only).

This is deliberately not a general Markdown parser. Legacy migration accepts headings,
fences and comments, and refuses HTML/container syntax it cannot safely interpret.
New installations use explicit ownership markers instead of inferred section bounds.
"""

import argparse
import base64
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import sys
import tempfile


BEGIN = "<!-- claude-token-saver:begin -->"
END = "<!-- claude-token-saver:end -->"
REFERENCE = Path(__file__).resolve().parents[1] / "references" / "rules.md"
CATEGORIES = {
    "communication": "Communication Style",
    "workflow": "Agent Workflow",
    "formatting": "Formatting and Error Handling",
}
LEVELS = ("light", "medium", "full")
ATX = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?)|[ \t]*)$")
FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
SETEXT = re.compile(r"^ {0,3}(=+|-+)[ \t]*$")
CONTAINER = re.compile(r"^ {0,3}(?:>|[-+*][ \t]+|\d+[.)][ \t]+)")


class UnsafeMerge(ValueError):
    pass


def digest(data):
    return hashlib.sha256(data).hexdigest()


def render(categories, level="light", model="general"):
    """Select literal bullets from the maintained reference; no model rewriting."""
    if not categories or len(set(categories)) != len(categories):
        raise ValueError("Select at least one category, without duplicates.")
    if any(c not in CATEGORIES for c in categories):
        raise ValueError("Unknown category. Use communication, workflow, formatting.")
    if level not in LEVELS or model not in ("general", "opus-5"):
        raise ValueError("Unknown conciseness level or model.")
    sections = {}
    section = None
    tier = None
    for line in REFERENCE.read_text(encoding="utf-8").splitlines():
        if line.startswith("## Category: "):
            section = line.removeprefix("## Category: ")
            tier = None
        elif line == "## Model: Claude Opus 5":
            section, tier = "Claude Opus 5 Workflow", None
        elif line.startswith("## "):
            section, tier = None, None
        elif line.startswith("### "):
            tier = line[4:].lower()
        elif line.startswith("- ") and section:
            sections.setdefault((section, tier), []).append(line)

    output = [BEGIN, "## Token Efficiency", "",
              "<!-- Generated by claude-token-saver; edit freely inside the markers. -->",
              "<!-- Adapted from drona23/claude-token-efficient (MIT); see plugin THIRD_PARTY_NOTICES.md. -->",
              f"<!-- Target model: {model} -->"]
    for category, title in CATEGORIES.items():
        if category not in categories:
            continue
        tiers = LEVELS[:LEVELS.index(level) + 1] if category == "communication" else (None,)
        bullets = []
        for selected_tier in tiers:
            selected = sections.get((title, selected_tier))
            if not selected:
                raise ValueError(f"Missing reference rules: {title}, {selected_tier}")
            bullets.extend(selected)
        output.extend(["", "### " + title, "", *bullets])
    if model == "opus-5" and "workflow" in categories:
        bullets = sections.get(("Claude Opus 5 Workflow", None))
        if not bullets:
            raise ValueError("Missing Opus 5 reference rules.")
        output.extend(["", "### Claude Opus 5 Workflow", "", *bullets])
    return "\n".join([*output, "", END, ""])


def scan(text):
    """Return line offsets, headings and marker spans, or reject ambiguous Markdown.

    Indented code is ignored. Blockquotes and list items reset paragraph detection;
    indented headings/fences after a container are ambiguous and require manual migration.
    Raw HTML other than comments is refused rather than guessing its block boundaries.
    """
    lines = text.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))
    headings, spans = [], []
    fence = None
    comment = False
    start = None
    paragraph = None
    container = False
    for i, raw in enumerate(lines):
        line = raw.rstrip("\r\n")
        if i == 0:
            line = line.removeprefix("\ufeff")
        if fence:
            if re.fullmatch(r" {0,3}" + re.escape(fence[0]) + "{" + str(fence[1]) + r",}[ \t]*", line):
                fence = None
            continue
        if comment:
            if "-->" in line:
                if line.split("-->", 1)[1].strip():
                    raise UnsafeMerge("Content after an HTML comment needs manual migration.")
                comment = False
            continue
        if line.startswith(("    ", "\t")):
            paragraph = None
            continue
        if line in (BEGIN, END):
            paragraph = None
            if line == BEGIN:
                if start is not None:
                    raise UnsafeMerge("Nested ownership markers; repair them before retrying.")
                start = i
            else:
                if start is None:
                    raise UnsafeMerge("End marker without begin marker.")
                spans.append((start, i + 1))
                start = None
            continue
        stripped = line.lstrip(" ")
        if stripped.startswith("<!--"):
            paragraph = None
            if "-->" in stripped[4:]:
                if stripped.split("-->", 1)[1].strip():
                    raise UnsafeMerge("Content after an HTML comment needs manual migration.")
            else:
                comment = True
            continue
        if stripped.startswith("<") or "<!--" in line:
            raise UnsafeMerge("HTML outside standalone comments needs manual migration.")
        if i and not lines[i - 1].strip() and line and not line.startswith(" "):
            container = False
        if CONTAINER.match(line):
            container, paragraph = True, None
            # A nested fence could contain unindented lookalike headings.
            if re.search(r"`{3,}|~{3,}|claude-token-saver:(?:begin|end)", line):
                raise UnsafeMerge("Nested fences or ownership markers need manual migration.")
            continue
        opening = FENCE.match(line)
        heading = ATX.match(line)
        underline = SETEXT.match(line)
        if container and line.startswith(" ") and (opening or heading or underline):
            raise UnsafeMerge("A heading or fence inside a list needs manual migration.")
        if opening:
            marker, info = opening.groups()
            if marker[0] == "`" and "`" in info:
                raise UnsafeMerge("Ambiguous backtick fence.")
            fence, paragraph, container = (marker[0], len(marker)), None, False
        elif heading:
            title = re.sub(r"[ \t]+#+[ \t]*$", "", heading[2] or "").strip()
            headings.append((i, len(heading[1]), title))
            paragraph, container = None, False
        elif underline and paragraph is not None:
            title = " ".join(l.strip() for l in lines[paragraph:i])
            headings.append((paragraph, 1 if underline[1][0] == "=" else 2, title))
            paragraph, container = None, False
        elif not line.strip() or underline or re.fullmatch(r" {0,3}(?:\*[ \t]*){3,}", line):
            paragraph = None
        else:
            if not container:
                paragraph = i if paragraph is None else paragraph
    if fence or comment or start is not None:
        raise UnsafeMerge("Unclosed fence, HTML comment or ownership marker; file left untouched.")
    return lines, offsets, headings, spans


def merge(original, section):
    """Replace owned spans, preserving every byte outside them. None removes rules."""
    if original.startswith(b"\xef\xbb\xbf"):
        return b"\xef\xbb\xbf" + merge(original[3:], section)
    text = original.decode("utf-8")
    if "\x00" in text or "\r" in text.replace("\r\n", ""):
        raise UnsafeMerge("Expected a UTF-8 Markdown file with LF or CRLF newlines.")
    lines, offsets, headings, spans = scan(text)
    owned = list(spans)
    for index, (line, level, title) in enumerate(headings):
        if any(a <= line < b for a, b in spans):
            continue
        if "token efficiency" not in title.casefold():
            continue
        if level != 2 or title != "Token Efficiency":
            raise UnsafeMerge("Renamed legacy Token Efficiency heading; mark its owned block manually before retrying.")
        end = next((n for n, depth, _ in headings[index + 1:] if depth <= 2), len(lines))
        if any(line < b and end > a for a, b in spans):
            raise UnsafeMerge("Legacy section overlaps an owned block; migrate manually.")
        # Leave the original separator before the next section outside the owned span.
        while end > line + 1 and not lines[end - 1].strip():
            end -= 1
        owned.append((line, end))
    owned.sort()
    for (_, end), (start, _) in zip(owned, owned[1:]):
        if end > start:
            raise UnsafeMerge("Overlapping sections; migrate manually.")
    newline = "\r\n" if "\r\n" in text else "\n"
    replacement = section.replace("\n", newline) if section is not None else ""
    if not owned:
        if not replacement:
            return original
        if not text:
            text = "# CLAUDE.md" + newline
        separator = "" if text.endswith(newline * 2) else newline if text.endswith(newline) else newline * 2
        return (text + separator + replacement).encode("utf-8")
    parts, cursor = [], 0
    for index, (start, end) in enumerate(owned):
        parts.append(text[cursor:offsets[start]])
        if index == 0:
            parts.append(replacement)
        cursor = offsets[end]
    parts.append(text[cursor:])
    return "".join(parts).encode("utf-8")


def snapshot(target):
    """Refuse links rather than silently changing link semantics during atomic replace."""
    try:
        info = target.lstat()
    except FileNotFoundError:
        return None, None
    if not stat.S_ISREG(info.st_mode) or info.st_nlink != 1:
        raise UnsafeMerge("Target must be a regular file, not a symlink or hard link.")
    return target.read_bytes(), stat.S_IMODE(info.st_mode)


def preview(target, plan_path, section):
    target = target.expanduser().absolute()
    # Pin the parent location so a changed directory symlink cannot redirect apply.
    target = target.parent.resolve() / target.name
    if plan_path.resolve() == target:
        raise UnsafeMerge("The temporary plan must be a different file from the target.")
    before, _ = snapshot(target)
    after = merge(before or b"", section)
    if after == (before or b""):
        print("No changes needed.")
        return
    plan = {
        "version": 1, "target": str(target),
        "before_sha256": digest(before) if before is not None else None,
        "after_base64": base64.b64encode(after).decode("ascii"),
    }
    data = (json.dumps(plan, indent=2) + "\n").encode("utf-8")
    # Exclusive creation prevents a typo or symlink from overwriting another file.
    fd = os.open(plan_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "wb") as output:
        output.write(data)
    diff = difflib.unified_diff((before or b"").decode("utf-8").splitlines(keepends=True),
                                after.decode("utf-8").splitlines(keepends=True),
                                fromfile=str(target), tofile=str(target) + " (proposed)")
    for line in diff:
        sys.stdout.write(line)
        if not line.endswith("\n"):
            sys.stdout.write("\n\\ No newline at end of file\n")
    print(f"\nPlan: {plan_path}\nApproval digest: {digest(data)}")


def apply(plan_path, approval):
    data = plan_path.read_bytes()
    if digest(data) != approval:
        raise UnsafeMerge("Plan changed since preview; generate and review a new preview.")
    plan = json.loads(data)
    if plan["version"] != 1:
        raise ValueError("Unsupported plan version.")
    target = Path(plan["target"])
    if not target.is_absolute() or target.parent.resolve() != target.parent:
        raise UnsafeMerge("Target directory changed since preview.")
    before, mode = snapshot(target)
    if (digest(before) if before is not None else None) != plan["before_sha256"]:
        raise UnsafeMerge("Target changed since preview; generate and review a new preview.")
    after = base64.b64decode(plan["after_base64"], validate=True)
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".claude-token-saver-", dir=target.parent)
    try:
        with os.fdopen(fd, "wb") as output:
            output.write(after)
            output.flush()
            os.fsync(output.fileno())
        os.chmod(name, mode if mode is not None else 0o600)
        # Catch edits during preparation too; this is not a filesystem locking protocol.
        if snapshot(target)[0] != before:
            raise UnsafeMerge("Target changed while preparing the write; preview again.")
        os.replace(name, target)
    finally:
        if os.path.exists(name):
            os.unlink(name)
    print(f"Updated {target}")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    if sys.version_info < (3, 9):
        parser.error("Python 3.9 or newer is required; target left untouched.")
    commands = parser.add_subparsers(dest="command", required=True)
    proposed = commands.add_parser("preview", help="Write a private plan and print its diff; never edit the target")
    proposed.add_argument("--target", required=True, type=Path)
    proposed.add_argument("--plan", required=True, type=Path, help="New file inside a private temporary directory")
    proposed.add_argument("--categories", default="communication")
    proposed.add_argument("--level", choices=LEVELS, default="light")
    proposed.add_argument("--model", choices=("general", "opus-5"), default="general")
    proposed.add_argument("--remove", action="store_true", help="Preview removal of generated blocks")
    accepted = commands.add_parser("apply", help="Apply the exact reviewed plan after user confirmation")
    accepted.add_argument("--plan", required=True, type=Path)
    accepted.add_argument("--approve", required=True, help="Approval digest printed by preview")
    args = parser.parse_args(argv)
    try:
        if args.command == "preview":
            section = None if args.remove else render(args.categories.split(","), args.level, args.model)
            preview(args.target, args.plan, section)
        else:
            apply(args.plan, args.approve)
    except (OSError, ValueError, KeyError, UnicodeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
